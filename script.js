const el = document.getElementById("prediction");
const sound = document.getElementById("sound");

const text = predictions[Math.floor(Math.random() * predictions.length)];

let i = 0;

// typing ефект
function typeEffect() {
  if (i < text.length) {
    el.textContent += text[i];
    i++;
    setTimeout(typeEffect, 20);
  }
}

// запуск
setTimeout(() => {

  // 📳 ВІБРАЦІЯ
  if (navigator.vibrate) {
    navigator.vibrate([100, 50, 100]);
  }

  // 🔊 ЗВУК (потрібна взаємодія користувача на iPhone, але часто працює через NFC відкриття)
  sound.volume = 0.3;
  sound.play().catch(() => {});

  el.classList.add("show");
  typeEffect();

}, 400);

// glow після появи
setTimeout(() => {
  el.classList.add("glow");
}, 3000);
